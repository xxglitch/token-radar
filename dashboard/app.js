// Launch Radar's dashboard. It reads window.RADAR (written beside dashboard/
// by main.ts) and renders the ranked board, filters, a per-protocol detail
// drawer with the model's own inputs and the protocol's farm plan, and the
// live-token view the calibration comes from. No network: every byte it shows
// is in data.js, and the page recomputes each row's implied value from the
// snapshot figures, so the code and the board's data are visibly the same
// arithmetic.
